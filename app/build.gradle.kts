                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        // The only build with the Debug log. It's its own app, "IV Lens dev", so it installs next to
